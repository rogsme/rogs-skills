async (page) => {
  const config = __CONFIG__;
  const external = [];
  page.__presentPlanExternal = external;
  await page.context().route("**/*", async (route) => {
    const url = new URL(route.request().url());
    if (url.hostname === "127.0.0.1") return route.continue();
    external.push(url.href);
    return route.abort();
  });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(config.url);
  const frame = page.frameLocator("#artifact");
  await frame.getByRole("heading", { name: "ACM-123: Pagination", exact: true }).waitFor();
  const warning = frame.locator(".review-warning").filter({ hasText: "Not reviewed:" });
  await warning.waitFor();
  if (await frame.locator("script:not([src])").count()) throw new Error("The plan executed source HTML.");
  if (await frame.locator("img").count()) throw new Error("Remote image was not rendered as a reference.");
  if (!(await frame.locator("table").textContent()).includes("Empty page test")) throw new Error("Review finding missing.");
  await frame.getByText(/This diagram needs local-only source/).waitFor();
  const whiteboardHost = frame.locator('iframe[data-lavish-ui="whiteboard-inline"]');
  await whiteboardHost.waitFor({ timeout: 30_000 });
  await page.locator("#layoutGateOverlay").waitFor({ state: "hidden", timeout: 30_000 });
  await frame.getByText("Preserve the current response format.", { exact: true }).click();
  const card = frame.locator("textarea");
  await card.fill("Keep the response format stable.");
  await card.press("Enter");
  await page.locator("#queuedLog").getByText("Keep the response format stable.", { exact: true }).waitFor();
  await whiteboardHost.click({ position: { x: 150, y: 180 } });
  const whiteboard = whiteboardHost.contentFrame();
  await whiteboard.locator("#wbNote").fill("Add a retry annotation to the plan.");
  await whiteboard.locator('[data-testid="toolbar-rectangle"]').click({ force: true });
  const canvas = whiteboard.locator("canvas.interactive");
  const bounds = await canvas.boundingBox();
  if (!bounds) throw new Error("Editable whiteboard canvas unavailable.");
  await page.mouse.move(bounds.x + 70, bounds.y + 90);
  await page.mouse.down();
  await page.mouse.move(bounds.x + 140, bounds.y + 150, { steps: 6 });
  await page.mouse.up();
  await whiteboard.locator("#wbQueue").click();
  await page.locator("#queuedLog").getByText(/Add a retry annotation/).waitFor({ timeout: 30_000 });
  await page.locator("#send").click();
  await page.setViewportSize({ width: 390, height: 844 });
  const artifact = page.frames().find((candidate) => candidate.url().includes("/artifact/"));
  const geometry = await artifact.evaluate(() => ({ width: innerWidth, content: document.documentElement.scrollWidth }));
  if (geometry.content > geometry.width + 1) throw new Error(`Mobile page overflows: ${JSON.stringify(geometry)}`);
  await page.setViewportSize({ width: 1440, height: 1000 });
  if (external.length) throw new Error(`External asset requests: ${external.join(", ")}`);
  return { passed: true, localAssets: true, annotationSent: true, whiteboardEdited: true, mobile: geometry };
}
